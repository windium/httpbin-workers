// Rasterizes the original vector illustrations in assets/images/ and embeds
// them (base64) in src/assets/images.js for the /image/* endpoints.
//   pig.svg    -> PNG   (256x256)
//   jackal.svg -> JPEG  (480x320)
//   wolf.svg   -> WebP  (480x320)
//   logo.svg   -> served verbatim as image/svg+xml
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'assets', 'images');
const dist = join(src, 'dist');
const out = join(root, 'src', 'assets', 'images.js');

// Rasterize at 4x the SVG's intrinsic size, then downsample for clean edges.
const SUPERSAMPLE = 4;

async function render(name, width, height, encode) {
  const svg = await readFile(join(src, name));
  const img = sharp(svg, { density: 72 * SUPERSAMPLE })
    .resize(width, height, { fit: 'fill', kernel: 'lanczos3' });
  return encode(img).toBuffer();
}

const [png, jpeg, webp, svg] = await Promise.all([
  render('pig.svg', 256, 256, (i) => i.png({ compressionLevel: 9, palette: true, quality: 95, dither: 0.6, effort: 10 })),
  render('jackal.svg', 480, 320, (i) => i.flatten({ background: '#000' }).jpeg({ quality: 85, mozjpeg: true, chromaSubsampling: '4:4:4' })),
  render('wolf.svg', 480, 320, (i) => i.webp({ quality: 85, effort: 6, smartSubsample: true })),
  readFile(join(src, 'logo.svg'), 'utf8'),
]);

await mkdir(dist, { recursive: true });
await mkdir(dirname(out), { recursive: true });
await Promise.all([
  writeFile(join(dist, 'pig.png'), png),
  writeFile(join(dist, 'jackal.jpg'), jpeg),
  writeFile(join(dist, 'wolf.webp'), webp),
]);

const js = `// Generated by scripts/build-images.mjs - do not edit by hand.
export const PNG = '${png.toString('base64')}';
export const JPEG = '${jpeg.toString('base64')}';
export const WEBP = '${webp.toString('base64')}';
export const SVG = ${JSON.stringify(svg.trim())};
`;
await writeFile(out, js);

const kb = (b) => `${(b.length / 1024).toFixed(1)} KB`;
console.log(`pig.png ${kb(png)}, jackal.jpg ${kb(jpeg)}, wolf.webp ${kb(webp)}, logo.svg ${kb(Buffer.from(svg))}`);
console.log(`wrote ${out}`);
